    case searchSessions = "navigator.search"
    case newSession = "navigator.new-session"
    case filterSessions = "navigator.filter"
    case projectActions = "navigator.project-actions"
    case addContext = "composer.add-context"
    case send = "composer.send"
    case stopRun = "composer.stop-run"
    case findAndReplace = "editor.find-and-replace"
    case save = "editor.save"
    case newTerminal = "terminal.new"
