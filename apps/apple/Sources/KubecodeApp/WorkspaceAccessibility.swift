        case .showNavigator: "Show Navigator"
        case .hideNavigator: "Hide Navigator"
        case .searchSessions: "Search Sessions"
        case .newSession: "New Session"
        case .filterSessions: "Filter Sessions"
        case .projectActions: "Project Actions"
        case .addContext: "Add Context"
